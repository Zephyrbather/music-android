val LocalStrings = staticCompositionLocalOf { chineseStrings }

@Composable
fun ProvideLocalizedStrings(
    language: AppLanguage,
    content: @Composable () -> Unit
) {
    CompositionLocalProvider(
        LocalStrings provides when (language) {
            AppLanguage.CHINESE -> chineseStrings
            AppLanguage.ENGLISH -> englishStrings
        },
        content = content
    )
}

fun ThemeModeTitle(mode: com.musicplayer.app.domain.repository.ThemeMode, strings: AppStrings): String {
    return when (mode) {
        com.musicplayer.app.domain.repository.ThemeMode.SYSTEM -> strings.system
        com.musicplayer.app.domain.repository.ThemeMode.LIGHT -> strings.light
        com.musicplayer.app.domain.repository.ThemeMode.DARK -> strings.dark
    }
}

fun ThemeStyleTitle(style: ThemeStyle, strings: AppStrings): String {
    return when (style) {
        ThemeStyle.CLASSIC -> strings.classicTheme
        ThemeStyle.OCEAN -> strings.oceanTheme
        ThemeStyle.FOREST -> strings.forestTheme
        ThemeStyle.ROSE -> strings.roseTheme
        ThemeStyle.MONO -> strings.monoTheme
        ThemeStyle.IMMERSIVE -> strings.immersiveTheme
    }
}

